-- ==============================================================================
-- RESET TOTAL & INISIALISASI DATABASE GEMAS GALORE (SUPABASE)
-- PERINGATAN: Skrip ini akan menghapus tabel lama & membuat ulang seluruh struktur database dari nol.
-- Aman dijalankan di Supabase SQL Editor tanpa error "policy already exists".
-- ==============================================================================

-- 1. HAPUS TABEL LAMA DENGAN BERSIH (CASCADE)
DROP TABLE IF EXISTS public.analytics_clicks CASCADE;
DROP TABLE IF EXISTS public.site_settings CASCADE;
DROP TABLE IF EXISTS public.resellers CASCADE;
DROP TABLE IF EXISTS public.messages CASCADE;
DROP TABLE IF EXISTS public.products CASCADE;

-- 2. TABEL PRODUK (products)
CREATE TABLE public.products (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT NOT NULL CHECK (category IN ('hijab', 'merchandise', 'souvenir')),
    price TEXT NOT NULL,
    image_url TEXT NOT NULL,
    badge TEXT DEFAULT 'Koleksi',
    description TEXT,
    material TEXT,
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. TABEL PESAN MASUK DARI WEBSITE (messages)
CREATE TABLE public.messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    phone TEXT,
    message TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. TABEL PENDAFTARAN RESELLER (resellers)
CREATE TABLE public.resellers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT NOT NULL,
    city TEXT,
    status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. TABEL ANALITIK PELACAKAN KLIK (analytics_clicks)
CREATE TABLE public.analytics_clicks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type TEXT NOT NULL, -- 'product_click', 'marketplace_click', 'whatsapp_click'
    target_name TEXT NOT NULL, -- Nama produk atau marketplace (contoh: Shopee, Hijab Paris, dll.)
    category TEXT DEFAULT 'general',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 6. TABEL PENGATURAN TOKO (site_settings)
CREATE TABLE public.site_settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 7. AKTIFKAN ROW LEVEL SECURITY (RLS)
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.resellers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.analytics_clicks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.site_settings ENABLE ROW LEVEL SECURITY;

-- 8. KEBIJAKAN AKSES (POLICIES)
-- A. Produk: Publik bisa melihat, siapapun dengan kunci project bisa mengelola (tambah/edit/hapus)
CREATE POLICY "Public read products" 
ON public.products FOR SELECT 
USING (true);

CREATE POLICY "Allow all modifications on products" 
ON public.products FOR ALL 
USING (true) 
WITH CHECK (true);

-- B. Pesan Masuk: Publik bisa kirim, pengelola bisa melihat dan menghapus
CREATE POLICY "Public can send messages" 
ON public.messages FOR INSERT 
WITH CHECK (true);

CREATE POLICY "Allow read messages" 
ON public.messages FOR SELECT 
USING (true);

CREATE POLICY "Allow delete messages" 
ON public.messages FOR DELETE 
USING (true);

-- C. Reseller: Publik bisa mendaftar, pengelola bisa melihat & update status
CREATE POLICY "Public can register reseller" 
ON public.resellers FOR INSERT 
WITH CHECK (true);

CREATE POLICY "Allow manage resellers" 
ON public.resellers FOR ALL 
USING (true) 
WITH CHECK (true);

-- D. Analitik Klik: Pengunjung bisa merekam klik, admin bisa melihat data untuk grafik
CREATE POLICY "Public can record clicks" 
ON public.analytics_clicks FOR INSERT 
WITH CHECK (true);

CREATE POLICY "Allow read analytics" 
ON public.analytics_clicks FOR SELECT 
USING (true);

CREATE POLICY "Allow delete analytics" 
ON public.analytics_clicks FOR DELETE 
USING (true);

-- E. Pengaturan Toko: Publik bisa membaca nomor WA/link Shopee, admin bisa update
CREATE POLICY "Public can view settings" 
ON public.site_settings FOR SELECT 
USING (true);

CREATE POLICY "Allow manage settings" 
ON public.site_settings FOR ALL 
USING (true) 
WITH CHECK (true);

