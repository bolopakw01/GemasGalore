-- ========================================================
-- DATABASE SCHEMA: GEMAS GALORE (SUPABASE)
-- ========================================================
-- Lengkap dengan Pelacakan Analitik & Pengaturan Toko
-- Aman dijalankan berulang kali (Idempotent / No Errors)
-- ========================================================

-- 1. Tabel Produk (products)
CREATE TABLE IF NOT EXISTS public.products (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT NOT NULL CHECK (category IN ('hijab', 'merchandise', 'souvenir')),
    price TEXT NOT NULL,
    image_url TEXT NOT NULL,
    badge TEXT DEFAULT 'Koleksi',
    description TEXT,
    material TEXT,
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Tabel Pesan Masuk Pelanggan (messages)
CREATE TABLE IF NOT EXISTS public.messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    phone TEXT,
    message TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Tabel Pendaftaran Reseller (resellers)
CREATE TABLE IF NOT EXISTS public.resellers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT NOT NULL,
    city TEXT,
    status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Tabel Pelacakan Klik & Analitik (analytics_clicks)
CREATE TABLE IF NOT EXISTS public.analytics_clicks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type TEXT NOT NULL, -- 'product_click', 'marketplace_click', 'whatsapp_click'
    target_name TEXT NOT NULL, -- contoh: 'Kerudung Paris Eksklusif', 'Shopee', 'WhatsApp'
    category TEXT DEFAULT 'general',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. Tabel Pengaturan Toko (site_settings)
CREATE TABLE IF NOT EXISTS public.site_settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

